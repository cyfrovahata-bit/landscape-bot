// Serve the built mini-app frontend (apps/miniapp-web/dist) from the same
// service, so the whole mini-app is one Railway service with one HTTPS URL
// to register in @BotFather. Falls back gracefully if it hasn't been built.
const webDist = path.resolve(__dirname, "../../miniapp-web/dist");
if (fs.existsSync(webDist)) {
  /**
   * Кеш роздачі — два протилежні правила, і саме їх відсутність робила деплой
   * невидимим для бригадирів.
   *
   * `index.html` — **ніколи не кешувати**. Це єдиний файл з незмінною
   * адресою, і саме в ньому написано, який хешований бандл вантажити. Без
   * заголовка express.static не каже про кеш нічого, і WebView Telegram
   * (особливо на Android) вирішує сам -- тримає стару сторінку, стара
   * сторінка тягне старий бандл, і бригадир тижнями не бачить того, що вже
   * місяць у продакшні. Це не теорія: 05.09 Альбіна не бачила розділу
   * «Повернені на редагування» через півтори години після деплою, і в логах
   * видно чому -- її застосунок навіть не запитував `/returned-days`.
   * Порада «закрити міні-апп повністю і відкрити знову» лікувала наслідок.
   *
   * Усе інше в `dist` — навпаки, кешувати рік: у назві файлу є хеш вмісту,
   * тож нова збірка це нові імена, а старі нікому не заважають.
   */
  const noStore = (res: express.Response) => res.setHeader("Cache-Control", "no-store, must-revalidate");

  app.use(
    express.static(webDist, {
      etag: true,
      setHeaders: (res, filePath) => {
        if (filePath.endsWith(".html")) noStore(res);
        else res.setHeader("Cache-Control", "public, max-age=31536000, immutable");
      },
    }),
  );
  app.get(/^(?!\/api).*/, (_req, res) => {
    noStore(res);
    res.sendFile(path.join(webDist, "index.html"));
  });
} else {
  console.warn(`[miniapp-server] no built frontend found at ${webDist} (run "npm run build -w apps/miniapp-web")`);
}

// Express 4 hands a rejected promise from an async route to nobody, and Node
// then treats the unhandled rejection as a fatal error. That is how one failed
// Google Drive upload took the whole mini-app offline for every foreman. These
// two nets keep a single bad request a single bad request.
app.use((err: unknown, _req: express.Request, res: express.Response, _next: express.NextFunction) => {
  console.error("[miniapp-server] unhandled route error", err);
  if (!res.headersSent) res.status(500).json({ error: "Внутрішня помилка сервера" });
});

process.on("unhandledRejection", (reason) => {
  // Deliberately does NOT exit: the request that caused it is already lost,
  // but the day every other brigade is running does not have to be.
  console.error("[miniapp-server] unhandled rejection", reason);
});

async function main() {
  await runMigrations();

  // One-time carry-over of the БУХЗВІТ export keys out of the old
  // БУХЗВІТ_META tab. No-ops once the table has rows (and once the tab is
  // gone), and must never take the server down with it -- a missing key
  // costs a duplicate export at worst, a failed boot costs the whole day.
  importAccountingKeysFromSheet().catch((e) =>
    console.error(`[accounting] key import skipped: ${(e as Error).message}`),
  );

  // Журнал дій: прибрати файли, старші за місяць, щоб волюм не заповнився
  // мовчки. Тимчасове, разом з рештою журналу.
  pruneUiLogs();

  const port = Number(process.env.PORT || 3001);
  app.listen(port, () => {
    console.log(`[miniapp-server] listening on :${port}`);
  });

  startSyncLoop(config.syncIntervalMs);
  await setupTelegramWebhook();
}

main().catch((err) => {
  console.error("[miniapp-server] fatal startup error", err);
  process.exit(1);
});
