const WORKING_DATA_SHEETS = [ACCOUNTING_SHEET] as const;

// Full reset of a test run's accumulated data, so real-world testing can
// start from a clean slate without hand-writing SQL each time. Working data
// is Postgres-only, so this now empties the tables and nothing else; use
// /internal/reset-all when БУХЗВІТ should go too.
app.post("/internal/reset-working-data", requireBotToken, async (_req, res) => {
  try {
    const countQuery = WORKING_DATA_TABLES.map((t) => `SELECT '${t}' AS "table", count(*)::int AS rows FROM ${t}`).join(" UNION ALL ");
    const before = await db.execute(sql.raw(countQuery));
    // TRUNCATE rather than DELETE: it also resets the serial id sequences, so
    // a cleared database starts numbering from 1 like a fresh one. No table
    // here is referenced by a foreign key, so no CASCADE is needed.
    await db.execute(sql.raw(`TRUNCATE TABLE ${WORKING_DATA_TABLES.join(", ")} RESTART IDENTITY`));
    console.log(`[maintenance] working data cleared: ${JSON.stringify(before)}`);
    res.json({ ok: true, cleared: before });
  } catch (e) {
    res.status(500).json({ error: (e as Error).message });
  }
});

/**
 * POST /internal/reset-foreman — прибирає дані ОДНОГО бригадира.
 *
 *   { "foremanTgId": 123456789 }                      усі його дні
 *   { "foremanTgId": 123456789, "date": "2026-09-05" } тільки цей день
 *
 * Навіщо окремо від reset-all: той чистить ПО ДАТІ, а в один день працює
 * кілька бригад. Тестовий прогін треба вміти прибрати, не зачепивши чужий
 * реальний день і чужі гроші.
 *
 * БУХЗВІТ не має колонки бригадира — там тільки дата, працівник і обʼєкт.
 * Тому, як і для timesheet_entries, чиї це рядки, кажуть події самого дня:
 * беремо з них обʼєкти й людей і видаляємо перетин. Обмеження в цього
 * прийому одне й давно відоме: якщо ТОГО САМОГО дня інша бригада працювала
 * на ТОМУ САМОМУ обʼєкті з ТІЄЮ САМОЮ людиною, її рядок теж підпаде.
 * Для тестової бригади зі своїми людьми цього не станеться.
 *
 * Аркуш чистимо ПЕРШИМ і лише тоді базу: якщо Google відмовив, краще
 * лишити все як є, ніж стерти базу й лишити гроші в БУХЗВІТі без сліду.
 */
app.post("/internal/reset-foreman", requireBotToken, async (req, res) => {
  const body = (req.body ?? {}) as { foremanTgId?: number | string; date?: string };
  const rawId = String(body.foremanTgId ?? "").trim();
  if (!/^\d+$/.test(rawId)) {
    res.status(400).json({ error: "foremanTgId обовʼязковий (число)" });
    return;
  }
  const tgId = BigInt(rawId);
  const date = String(body.date ?? "").trim();
  if (date && !/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    res.status(400).json({ error: "date у форматі YYYY-MM-DD" });
    return;
  }

  const byForeman = (col: any) => (date ? and(eq(col.foremanTgId, tgId), eq(col.date, date)) : eq(col.foremanTgId, tgId));

  try {
    const events = await db.select().from(schema.events).where(byForeman(schema.events));

    // Що саме належить цьому бригадиру: дати, обʼєкти, люди.
    const dates = new Set<string>();
    const objectIds = new Set<string>();
    const employeeIds = new Set<string>();
    for (const e of events) {
      if (e.date) dates.add(e.date);
      try {
        const payload = JSON.parse(e.payload ?? "{}") as {
          objects?: { objectId?: string; sessions?: { employeeId?: string }[] }[];
          employeeIds?: string[];
        };
        for (const o of payload.objects ?? []) {
          if (o.objectId) objectIds.add(o.objectId);
          for (const sess of o.sessions ?? []) if (sess.employeeId) employeeIds.add(sess.employeeId);
        }
        for (const id of payload.employeeIds ?? []) employeeIds.add(id);
      } catch {
        // побитий payload не має зупиняти прибирання решти
      }
    }

    // У БУХЗВІТі стоять ІМЕНА, не id — тож перекладаємо через довідники.
    let accountingRowsDeleted = 0;
    if (dates.size && objectIds.size && employeeIds.size) {
      const [employeeRows, objectRows] = await Promise.all([
        db.select().from(schema.employees),
        db.select().from(schema.objects),
      ]);
      const norm = (v: string) => v.trim().toLowerCase();
      const employeeNames = new Set(
        employeeRows.filter((r) => employeeIds.has(r.id)).map((r) => norm(r.name)),
      );
      const objectNames = new Set(objectRows.filter((r) => objectIds.has(r.id)).map((r) => norm(r.name)));
      try {
        accountingRowsDeleted = await sheetsClient.deleteRowsWhere(ACCOUNTING_SHEET, (row, map) => {
          const d = sheetsClient.getCell(row, map, "Дата");
          if (!dates.has(d)) return false;
          if (!employeeNames.has(norm(sheetsClient.getCell(row, map, "Працівник")))) return false;
          return objectNames.has(norm(sheetsClient.getCell(row, map, "Об'єкт")));
        });
      } catch (e) {
        console.error("[maintenance] БУХЗВІТ clearing failed, Postgres left untouched", e);
        res.status(502).json({
          error: `Не вдалося очистити БУХЗВІТ: ${(e as Error).message}. Базу не чіпали — спробуйте ще раз.`,
        });
        return;
      }
    }

    // Тепер база. Все, що має колонку бригадира, — прямо по ній.
    const deleted: Record<string, number> = { "БУХЗВІТ (рядків)": accountingRowsDeleted };
    const drop = async (label: string, table: any, where: any) => {
      const rows = await db.delete(table).where(where).returning({ id: sql<number>`1` });
      deleted[label] = rows.length;
    };

    await drop("events", schema.events, byForeman(schema.events));
    await drop("reports", schema.reports, byForeman(schema.reports));
    await drop("allowances", schema.allowances, byForeman(schema.allowances));
    await drop("day_statuses", schema.dayStatuses, byForeman(schema.dayStatuses));
    await drop("odometer_days", schema.odometerDays, byForeman(schema.odometerDays));
    await drop("trip_progress", schema.tripProgress, byForeman(schema.tripProgress));
    await drop("accounting_exports", schema.accountingExports, byForeman(schema.accountingExports));

    // ТАБЕЛЬ бригадира не знає — той самий перетин, що й для БУХЗВІТу.
    if (dates.size && objectIds.size && employeeIds.size) {
      await drop(
        "timesheet_entries",
        schema.timesheetEntries,
        and(
          inArray(schema.timesheetEntries.date, [...dates]),
          inArray(schema.timesheetEntries.objectId, [...objectIds]),
          inArray(schema.timesheetEntries.employeeId, [...employeeIds]),
        ),
      );
    }

    // Плани й чернетка дати не мають (план без дати — це «наступний виїзд»),
    // тож вони йдуть лише при повному прибиранні бригадира.
    if (!date) {
      await drop("trip_plans", schema.tripPlans, eq(schema.tripPlans.foremanTgId, tgId));
      await drop("day_drafts", schema.dayDrafts, eq(schema.dayDrafts.foremanTgId, tgId));
      await drop("ui_actions", schema.uiActions, eq(schema.uiActions.tgId, tgId));
    }

    console.log(`[maintenance] reset-foreman tgId=${rawId} date=${date || "-"} ${JSON.stringify(deleted)}`);
    res.json({ ok: true, foremanTgId: rawId, date: date || null, deleted });
  } catch (e) {
    res.status(500).json({ error: (e as Error).message });
  }
});

/**
 * POST /internal/reset-all — wipes an entire test run: the sheets the program
 * writes, then the Postgres tables behind them.
 *
 * Dictionaries are NOT touched: КОРИСТУВАЧІ, ПРАЦІВНИКИ, ОБЄКТИ, РОБОТИ, АВТО,
 * ЛОГІСТИКА, МАТЕРІАЛИ, ІНСТРУМЕНТИ, НАЛАШТУВАННЯ are maintained by hand and
 * are the input, not the output.
 *
 * БУХЗВІТ goes first and Postgres only if it succeeded. Half a wipe is worse
 * than none: an emptied database with the accountant's report still listing
 * the day leaves the two disagreeing about what happened.
 */
app.post("/internal/reset-all", requireBotToken, async (req, res) => {
  // Optional surgical mode: keep one day, delete the rest. БУХЗВІТ carries a
  // "Дата" column and БУХЗВІТ_META encodes the date inside its key as
  // MINIAPP|<date>|<foreman>|..., so one date is the one thing that can be
  // matched consistently in both.
  const body = (req.body ?? {}) as { keepDate?: string; deleteUntil?: string };
  const isDate = (v: unknown) => typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v.trim());
  const keepDate = isDate(body.keepDate) ? String(body.keepDate).trim() : "";
  // The other way round: clear out everything up to and INCLUDING this date,
  // for trimming old test runs while today's work stays put.
  const deleteUntil = isDate(body.deleteUntil) ? String(body.deleteUntil).trim() : "";
  if (keepDate && deleteUntil) {
    res.status(400).json({ error: "Вкажіть щось одне: keepDate або deleteUntil" });
    return;
  }
  if ((body.keepDate && !keepDate) || (body.deleteUntil && !deleteUntil)) {
    res.status(400).json({ error: "Дата має бути у форматі YYYY-MM-DD" });
    return;
  }
  // ISO dates compare correctly as plain strings, which is why one format is
  // enforced above -- everything below leans on that.
  const rowMatches = (rowDate: string) => (keepDate ? rowDate !== keepDate : rowDate !== "" && rowDate <= deleteUntil);

  const sheetsCleared: Record<string, number> = {};
  try {
    for (const name of WORKING_DATA_SHEETS) {
      if (!keepDate && !deleteUntil) {
        sheetsCleared[name] = await sheetsClient.clearSheetData(name);
        continue;
      }
      sheetsCleared[name] = await sheetsClient.deleteRowsWhere(name, (row, map) =>
        rowMatches(String(sheetsClient.getCell(row, map, "Дата") ?? "").trim()),
      );
    }
  } catch (e) {
    console.error("[maintenance] sheet clearing failed, Postgres left untouched", e);
    res.status(502).json({
      error: `Не вдалося очистити аркуші: ${(e as Error).message}. Базу не чіпали — спробуйте ще раз.`,
      sheetsCleared,
    });
    return;
  }

  try {
    const countQuery = WORKING_DATA_TABLES.map((t) => `SELECT '${t}' AS "table", count(*)::int AS rows FROM ${t}`).join(" UNION ALL ");
    const before = await db.execute(sql.raw(countQuery));
    if (deleteUntil) {
      const cutoff = deleteUntil.replace(/'/g, "''");
      for (const t of DATED_WORKING_TABLES) {
        await db.execute(sql.raw(`DELETE FROM ${t} WHERE date <= '${cutoff}'`));
      }
    } else if (keepDate) {
      // Everything except that one day. trip_plans is deliberately LEFT ALONE:
      // plans are not trips, and deleting more than asked cannot be undone.
      for (const t of DATED_WORKING_TABLES) {
        await db.execute(sql.raw(`DELETE FROM ${t} WHERE date <> '${keepDate.replace(/'/g, "''")}'`));
      }
    } else {
      // TRUNCATE rather than DELETE: it also resets the serial id sequences.
      await db.execute(sql.raw(`TRUNCATE TABLE ${WORKING_DATA_TABLES.join(", ")} RESTART IDENTITY`));
    }
    const after = await db.execute(sql.raw(countQuery));
    console.log(
      `[maintenance] reset keepDate=${keepDate || "-"} deleteUntil=${deleteUntil || "-"} sheets=${JSON.stringify(sheetsCleared)}`,
    );
    res.json({
      ok: true,
      keepDate: keepDate || null,
      deleteUntil: deleteUntil || null,
      sheetsCleared,
      tablesBefore: before,
      tablesAfter: after,
    });
  } catch (e) {
    res.status(500).json({ error: (e as Error).message, sheetsCleared });
  }
});

/** Read-only: what days exist, so a wipe can be aimed before it is fired. */
app.get("/internal/data-summary", requireBotToken, async (_req, res) => {
  try {
    const rows = await db.execute(
      sql.raw(`SELECT e.date,
                      e.foreman_tg_id::text AS foreman_tg_id,
                      COALESCE(u.pib, '') AS foreman_name,
                      count(*) FILTER (WHERE e.type = 'RTS_SAVE')::int AS trips,
                      max(e.ts)::text AS last_event,
                      string_agg(DISTINCT e.status, ',') AS statuses
               FROM events e
               LEFT JOIN users u ON u.tg_id = e.foreman_tg_id
               GROUP BY e.date, e.foreman_tg_id, u.pib
               ORDER BY e.date DESC, last_event DESC`),
    );
    const plans = await db.execute(sql.raw("SELECT count(*)::int AS plans FROM trip_plans"));
    res.json({ days: rows, plans });
  } catch (e) {
    res.status(500).json({ error: (e as Error).message });
  }
});

